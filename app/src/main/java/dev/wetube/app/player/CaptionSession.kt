package dev.wetube.app.player

import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import dev.wetube.app.data.model.CaptionTrack
import dev.wetube.app.data.model.TranslationLanguage
import dev.wetube.app.data.model.VideoDetail
import dev.wetube.app.di.ServiceLocator
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Job
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.launch

/**
 * The caption state of whatever is currently in the player.
 *
 * Both the normal player and Shorts own one of these. Preferences (on/off,
 * language, translation) live in [dev.wetube.app.data.prefs.SettingsStore], so
 * the choice carries from one video to the next, exactly like the official
 * app's CC button does.
 */
class CaptionSession(
    private val locator: ServiceLocator,
    private val scope: CoroutineScope,
) {

    var tracks by mutableStateOf<List<CaptionTrack>>(emptyList())
        private set

    var translations by mutableStateOf<List<TranslationLanguage>>(emptyList())
        private set

    var cues by mutableStateOf<List<CaptionCue>>(emptyList())
        private set

    var enabled by mutableStateOf(false)
        private set

    var selected by mutableStateOf<CaptionTrack?>(null)
        private set

    var translateTo by mutableStateOf("")
        private set

    var loading by mutableStateOf(false)
        private set

    var error by mutableStateOf<String?>(null)
        private set

    private var job: Job? = null

    /** Called once the detail of a newly started video is known. */
    fun attach(detail: VideoDetail) {
        job?.cancel()
        tracks = detail.captions.tracks
        translations = detail.captions.translations
        cues = emptyList()
        error = null
        loading = false
        scope.launch {
            val prefs = locator.settings.settings.first()
            translateTo = prefs.captionTranslateTo
            selected = pick(prefs.captionLanguage)
            enabled = prefs.captionsEnabled && tracks.isNotEmpty()
            reload()
        }
    }

    fun setCaptionsEnabled(value: Boolean) {
        enabled = value
        if (!value) {
            job?.cancel()
            cues = emptyList()
            loading = false
            error = null
        } else {
            if (selected == null) selected = pick("")
            reload()
        }
        persist()
    }

    /** Picks a subtitle language. A non-blank [translate] turns captions on. */
    fun choose(track: CaptionTrack?, translate: String = translateTo) {
        selected = track
        translateTo = translate
        enabled = track != null
        reload()
        persist()
    }

    fun clearTranslation() = choose(selected, "")

    /** Current subtitle line, or null when captions are off or nothing is due. */
    fun captionAt(positionMs: Long): String? {
        if (!enabled) return null
        val list = cues
        if (list.isEmpty()) return null
        var low = 0
        var high = list.lastIndex
        while (low <= high) {
            val mid = (low + high) ushr 1
            val cue = list[mid]
            when {
                positionMs < cue.startMs -> high = mid - 1
                positionMs >= cue.endMs -> low = mid + 1
                else -> return cue.text
            }
        }
        return null
    }

    private fun pick(languageCode: String): CaptionTrack? =
        tracks.firstOrNull { it.languageCode == languageCode }
            ?: tracks.firstOrNull { !it.autoGenerated }
            ?: tracks.firstOrNull()

    private fun reload() {
        job?.cancel()
        val track = selected
        if (!enabled || track == null) {
            cues = emptyList()
            loading = false
            error = null
            return
        }
        loading = true
        error = null
        val language = translateTo
        job = scope.launch {
            runCatching { locator.captionLoader.load(track, language) }
                .onSuccess {
                    cues = it
                    error = null
                }
                .onFailure { failure ->
                    cues = emptyList()
                    // Machine translation is best-effort: YouTube occasionally
                    // answers a tlang request with an empty/rate-limited body,
                    // so fall back to the original track instead of leaving the
                    // viewer without any subtitles.
                    if (language.isNotBlank()) {
                        val original = runCatching { locator.captionLoader.load(track) }
                        if (original.isSuccess) {
                            cues = original.getOrDefault(emptyList())
                            error = "Auto-translate is unavailable right now; showing the original captions."
                        } else {
                            error = captionError(failure)
                        }
                    } else {
                        error = captionError(failure)
                    }
                }
            loading = false
        }
    }

    private fun captionError(failure: Throwable): String {
        val raw = failure.message.orEmpty()
        return when {
            raw.contains("HTTP 429") -> "YouTube is rate-limiting captions. Try again in a minute."
            raw.contains("No captions") || raw.contains("Empty caption") ->
                "This caption track is empty."
            raw.contains("HTTP 404") -> "This caption track is no longer available."
            else -> "Could not load captions."
        }
    }

    private fun persist() {
        val language = selected?.languageCode.orEmpty()
        val translate = translateTo
        val on = enabled
        scope.launch {
            locator.settings.update {
                it.copy(
                    captionsEnabled = on,
                    captionLanguage = language.ifBlank { it.captionLanguage },
                    captionTranslateTo = translate,
                )
            }
        }
    }
}
