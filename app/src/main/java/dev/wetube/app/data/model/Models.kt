package dev.wetube.app.data.model

import kotlinx.serialization.Serializable

/** A video as it appears in a feed, search result or related list. */
@Serializable
data class VideoItem(
    val id: String,
    val title: String,
    val channelName: String,
    val channelId: String = "",
    val thumbnail: String = "",
    val durationSeconds: Int = 0,
    val views: Long = 0,
    val publishedText: String = "",
    val live: Boolean = false,
)

/**
 * A subtitle track YouTube offers for a video. [baseUrl] is a timed-text URL
 * that already carries the signing parameters; adding `tlang=<code>` asks
 * YouTube for its machine translation of the same track.
 */
data class CaptionTrack(
    val languageCode: String,
    val name: String,
    val baseUrl: String,
    val autoGenerated: Boolean = false,
)

/** A language YouTube can machine-translate a caption track into. */
data class TranslationLanguage(
    val languageCode: String,
    val name: String,
)

data class CaptionSet(
    val tracks: List<CaptionTrack> = emptyList(),
    val translations: List<TranslationLanguage> = emptyList(),
) {
    val isEmpty: Boolean get() = tracks.isEmpty()
}

/** One concrete media track offered by a backend. */
data class StreamFormat(
    val url: String,
    val label: String,
    val mime: String,
    val bitrate: Long = 0,
    val height: Int = 0,
    val audio: Boolean = false,
)

/**
 * One dubbed audio rendition YouTube resolved for a video.
 *
 * A dub is not a track of the stream the player is handed: YouTube publishes
 * every language as its own adaptive audio format, so nothing inside a single
 * `MediaItem` can switch languages. Carrying the whole set on [Playback] is what
 * lets the picker offer the languages and the player be rebuilt on a pick.
 */
data class AudioStream(
    /** Progressive audio URL, signed like every other format URL. */
    val url: String,
    /** Container/codec of [url], e.g. `audio/mp4`. */
    val mime: String,
    /** ISO-639 code YouTube states, taken from `audioTrack.id` (`en` in `en.4`). */
    val languageCode: String = "",
    /** YouTube's own name for the dub ("English (US)"), "" when it gave none. */
    val displayName: String = "",
    /** True for the track YouTube flags `audioIsDefault`. */
    val isDefault: Boolean = false,
    /**
     * True for the recording's own language.
     *
     * YouTube lists the original's formats before any dub and does not always
     * flag it, so this is the row that starts playing when nothing else matches.
     */
    val original: Boolean = false,
)

/**
 * Everything the player needs. Backends differ wildly in what they expose, so
 * the player negotiates instead of assuming one container.
 *
 * [audioStreams] is the one field that is not a plain media list: it holds every
 * dub the backend resolved, and an empty list means the backend cannot resolve
 * dubs at all, which is exactly the behaviour of a single-audio video.
 */
data class Playback(
    val muxed: List<StreamFormat> = emptyList(),
    val videoOnly: List<StreamFormat> = emptyList(),
    val audioOnly: List<StreamFormat> = emptyList(),
    val hls: String? = null,
    val audioStreams: List<AudioStream> = emptyList(),
) {
    val isEmpty: Boolean get() = muxed.isEmpty() && videoOnly.isEmpty() && audioOnly.isEmpty() && hls == null

    /**
     * The distinct video resolutions this playback offers, highest first.
     * Muxed and adaptive tracks are merged, so a video that only ships a single
     * progressive file still reports one option.
     */
    val videoQualities: List<Int>
        get() = (muxed + videoOnly)
            .filter { it.url.isNotBlank() && it.height > 0 }
            .map { it.height }
            .distinct()
            .sortedDescending()
}

data class VideoDetail(
    val item: VideoItem,
    val description: String,
    val likes: Long,
    val subscribersText: String,
    val playback: Playback,
    val related: List<VideoItem>,
    val isLive: Boolean = false,
    val captions: CaptionSet = CaptionSet(),
    val comments: CommentThreadInfo = CommentThreadInfo(),
)

/**
 * Pointers to the video's comment section, taken from the same watch response
 * that already supplies likes and related videos. [continuation] and
 * [newestContinuation] are opaque tokens for the "Top" and "Newest" first
 * pages; a blank token means the backend cannot paginate comments natively.
 */
data class CommentThreadInfo(
    val continuation: String = "",
    val newestContinuation: String = "",
    val countText: String = "",
)

/** One page of comments plus the token for the next page, when there is one. */
data class CommentPage(
    val comments: List<Comment> = emptyList(),
    val next: String? = null,
)

data class ChannelInfo(
    val id: String,
    val name: String,
    val avatar: String = "",
    val banner: String = "",
    val description: String = "",
    val subscribersText: String = "",
    val videos: List<VideoItem> = emptyList(),
)

data class Comment(
    val author: String,
    val avatar: String = "",
    val text: String,
    val likes: Long = 0,
    val publishedText: String = "",
    val replyCount: Int = 0,
    val id: String = "",
    val liked: Boolean = false,
    val own: Boolean = false,
    val actions: CommentActions = CommentActions(),
    val replies: CommentReplies? = null,
)

/**
 * A pointer to one comment's replies.
 *
 * The replies are not on the page that shows the comment: the row carries only
 * a count and the opaque [token] that asks for them, and that token answers a
 * page of its own. [label] is the server's own wording for the count ("45
 * replies"), kept verbatim so the row and the page it opens agree.
 *
 * Only a top-level comment has one. A reply inside a thread arrives without
 * this, because a thread is one level deep by design — and that absence is
 * exactly what keeps a reply from offering a thread of its own.
 */
data class CommentReplies(
    val token: String = "",
    val label: String = "",
)

/**
 * The write commands YouTube handed out for one comment.
 *
 * Each field is the server's own opaque parameter, carried back verbatim:
 * [like] and [unlike] are the `action` a `comment/perform_comment_action`
 * request takes, and [reply] is the `createCommentParams` that places a new
 * comment underneath this one. They are minted per comment *and per session*,
 * which is why they are read off the answer instead of being built here.
 *
 * A signed-out answer carries none of them: YouTube offers no commands on a
 * page it does not know you on. [canLike] and [canReply] are false there, and
 * the sheet shows no buttons rather than a button that cannot do anything.
 */
data class CommentActions(
    val like: String? = null,
    val unlike: String? = null,
    val reply: String? = null,
) {
    val canLike: Boolean get() = like != null && unlike != null
    val canReply: Boolean get() = reply != null
}

/**
 * One page of results.
 *
 * [blocks] keeps the answer in the order it came in, so a Shorts shelf stays
 * where the search put it among the video rows; transports that have no shelves
 * leave it empty and the caller falls back to [videos].
 */
data class SearchResult(
    val videos: List<VideoItem>,
    val channels: List<ChannelInfo> = emptyList(),
    val nextPage: String? = null,
    val blocks: List<FeedBlock> = emptyList(),
)

/**
 * One page of the front-page feed, plus the token that asks for the next one.
 *
 * [nextPage] is opaque to the UI: it is whatever the backend needs to resume,
 * and `null` means the feed has ended (or the backend cannot page it at all).
 */
data class FeedPage(
    val videos: List<VideoItem>,
    val nextPage: String? = null,
)

/**
 * One entry in Home's chip bar.
 *
 * [token] is the opaque request that selects this chip, minted by the backend
 * that produced the bar; `null` means "the feed's own first page", which is how
 * the already-selected chip ("All") arrives. [selected] marks the one chip the
 * current feed belongs to, so the UI never has to guess from the title.
 */
data class FeedChip(
    val title: String,
    val token: String? = null,
    val selected: Boolean = false,
)

/**
 * A shelf inside a feed or a result page: one titled horizontal row.
 *
 * [isShorts] is carried by the shelf itself (YouTube marks the Shorts shelf with
 * its brand icon), not guessed from [title], because the title is localised and
 * viewers can rename nothing but see every language.
 */
data class FeedShelf(
    val title: String,
    val items: List<VideoItem>,
    val isShorts: Boolean = false,
)

/** One element of a page, in the order the answer returned it. */
sealed interface FeedBlock {
    data class Video(val video: VideoItem) : FeedBlock

    data class Shelf(val shelf: FeedShelf) : FeedBlock

    /** Every video this block shows; a shelf contributes all of its cards. */
    val videos: List<VideoItem>
        get() = when (this) {
            is Video -> listOf(video)
            is Shelf -> shelf.items
        }
}

/**
 * One page of Home: the chip bar, the ordered blocks, and the next-page token.
 *
 * The blocks are kept in feed order rather than flattened into a video list,
 * because a shelf's position among the videos is part of what the page looks
 * like: the Shorts shelf sits between two rows of videos and moves as the feed
 * changes. A transport that has no shelves simply returns [FeedBlock.Video]s.
 */
data class HomePage(
    val blocks: List<FeedBlock> = emptyList(),
    val chips: List<FeedChip> = emptyList(),
    val nextPage: String? = null,
) {
    /** Every video in the page, shelves included, de-duplicated in feed order. */
    val videos: List<VideoItem>
        get() = blocks.flatMap { it.videos }.distinctBy { it.id }
}
