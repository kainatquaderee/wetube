package dev.wetube.app.data.model

import kotlinx.serialization.Serializable

/** A video as it appears in a feed, search result or related list. */
@Serializable
data class VideoItem(
    val id: String,
    val title: String,
    val channelName: String,
    val channelId: String = "",
    val thumbnail: String = "",
    val durationSeconds: Int = 0,
    val views: Long = 0,
    val publishedText: String = "",
    val live: Boolean = false,
)

/**
 * A subtitle track YouTube offers for a video. [baseUrl] is a timed-text URL
 * that already carries the signing parameters; adding `tlang=<code>` asks
 * YouTube for its machine translation of the same track.
 */
data class CaptionTrack(
    val languageCode: String,
    val name: String,
    val baseUrl: String,
    val autoGenerated: Boolean = false,
)

/** A language YouTube can machine-translate a caption track into. */
data class TranslationLanguage(
    val languageCode: String,
    val name: String,
)

data class CaptionSet(
    val tracks: List<CaptionTrack> = emptyList(),
    val translations: List<TranslationLanguage> = emptyList(),
) {
    val isEmpty: Boolean get() = tracks.isEmpty()
}

/** One concrete media track offered by a backend. */
data class StreamFormat(
    val url: String,
    val label: String,
    val mime: String,
    val bitrate: Long = 0,
    val height: Int = 0,
    val audio: Boolean = false,
)

/**
 * Everything the player needs. Backends differ wildly in what they expose, so
 * the player negotiates instead of assuming one container.
 */
data class Playback(
    val muxed: List<StreamFormat> = emptyList(),
    val videoOnly: List<StreamFormat> = emptyList(),
    val audioOnly: List<StreamFormat> = emptyList(),
    val hls: String? = null,
) {
    val isEmpty: Boolean get() = muxed.isEmpty() && videoOnly.isEmpty() && audioOnly.isEmpty() && hls == null
}

data class VideoDetail(
    val item: VideoItem,
    val description: String,
    val likes: Long,
    val subscribersText: String,
    val playback: Playback,
    val related: List<VideoItem>,
    val isLive: Boolean = false,
    val captions: CaptionSet = CaptionSet(),
    val comments: CommentThreadInfo = CommentThreadInfo(),
)

/**
 * Pointers to the video's comment section, taken from the same watch response
 * that already supplies likes and related videos. [continuation] and
 * [newestContinuation] are opaque tokens for the "Top" and "Newest" first
 * pages; a blank token means the backend cannot paginate comments natively.
 */
data class CommentThreadInfo(
    val continuation: String = "",
    val newestContinuation: String = "",
    val countText: String = "",
)

/** One page of comments plus the token for the next page, when there is one. */
data class CommentPage(
    val comments: List<Comment> = emptyList(),
    val next: String? = null,
)

data class ChannelInfo(
    val id: String,
    val name: String,
    val avatar: String = "",
    val banner: String = "",
    val description: String = "",
    val subscribersText: String = "",
    val videos: List<VideoItem> = emptyList(),
)

data class Comment(
    val author: String,
    val avatar: String = "",
    val text: String,
    val likes: Long = 0,
    val publishedText: String = "",
    val replyCount: Int = 0,
    val id: String = "",
)

data class SearchResult(
    val videos: List<VideoItem>,
    val channels: List<ChannelInfo> = emptyList(),
    val nextPage: String? = null,
)
